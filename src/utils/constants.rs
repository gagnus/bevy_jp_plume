/// Size constants.
///
/// Nearly everything here is a [`Val::Em`](bevy::ui::Val::Em) stated in
/// px-at-the-standard-font (via [`size::em_from_px`]), so a container that sets a
/// bigger font gets chrome, spacing and rounding to match. What stays
/// [`Val::Px`](bevy::ui::Val::Px) is what should look identical at any size:
/// [`size::HAIRLINE`], the focus ring, and positions measured at runtime.
///
/// "Any size" is deliberate in both directions - a px value here tracks neither
/// the local font nor `RemSize`, so an app that scales its whole UI up still
/// gets one-pixel borders. That is the point of a hairline: it is a property of
/// the display, not of the type.
///
/// Anything em-sized needs an `EmSize`, which plume mirrors onto text-chain
/// nodes only - a node authoring em without one is a bug the debug-build
/// `warn_em_without_em_size` lint names for you.
pub mod size {
    use bevy::ui::{Val, Val2};

    use crate::font_styles::PlumeFontSize;

    /// The standard font size in pixels: the px the em constants were designed
    /// at (see [`em_from_px`]), and the value the `RemSize` resource is set to
    /// at plugin init. Runtime sizing reads `RemSize`, not this - an app is free
    /// to move it, and only the design ratios below stay pinned here.
    pub const MEDIUM_FONT_PX: f32 = 14.0;

    /// A length stated in px-at-standard-font but carried as `Val::Em`, so the
    /// chrome it sizes tracks the effective font.
    pub const fn em_from_px(px_at_standard_font: f32) -> Val {
        Val::Em(px_at_standard_font / MEDIUM_FONT_PX)
    }

    /// Common row size for buttons, sliders, spinners, etc.
    pub const ROW_HEIGHT: Val = em_from_px(24.0);

    /// Width and height of a checkbox
    pub const CHECKBOX_SIZE: Val = em_from_px(18.0);

    /// Height for pane headers
    pub const HEADER_HEIGHT: Val = em_from_px(30.0);

    /// Height for dialog headers
    pub const DIALOG_HEADER_HEIGHT: Val = em_from_px(40.0);

    /// Text size for dialog headers, as a multiple of the inherited
    /// size - set it as `InheritableFont { font_size: … }`.
    pub const DIALOG_HEADER_TEXT_SIZE: PlumeFontSize = PlumeFontSize::Em(1.25);

    /// Width and height of a radio button
    pub const RADIO_SIZE: Val = em_from_px(18.0);

    /// Size of a toggle switch
    pub const TOGGLE_SIZE: Val2 = Val2 {
        x: em_from_px(32.0),
        y: em_from_px(18.0),
    };

    /// Standard corner radius for controls and containers.
    pub const CORNER_RADIUS: Val = em_from_px(6.0);

    /// Tighter rounding for small controls.
    pub const CORNER_RADIUS_SMALL: Val = em_from_px(4.0);

    /// Rounding for dialog sized containers.
    pub const DIALOG_RADIUS: Val = em_from_px(8.0);

    /// Hairline thickness in px: borders stay one crisp pixel at any font size,
    /// so they are the one part of the look that never scales.
    pub(crate) const HAIRLINE_PX: f32 = 1.0;

    /// One crisp pixel - every border, divider and rule in the look. Also the
    /// unit for the odd padding or line width that wants to read as a hairline
    /// rather than as spacing.
    pub const HAIRLINE: Val = Val::Px(HAIRLINE_PX);

    /// Thickness of the accent underline marking the selected tab; it sits under
    /// text, so it scales with it.
    pub const TAB_INDICATOR_HEIGHT: Val = em_from_px(2.0);

    /// Height of a tab bar, a little higher than .
    pub const TAB_BAR_HEIGHT: Val = em_from_px(30.0);

    /// How far a crowded tab is squeezed before its strip scrolls instead - room
    /// for a leading icon and a stub of label, so an icon tab shrinks to about
    /// the glyph. A header carrying more than that wants its own, wider floor.
    pub const TAB_MIN_WIDTH: Val = Val::Em(2.5);

    const FOCUS_RING_WIDTH_PX: f32 = 2.0;
    const FOCUS_RING_OFFSET_PX: f32 = 2.0;

    /// Focus ring thickness; px with the other hairlines, so the ring reads the
    /// same on every control whatever font it sits in.
    pub const FOCUS_RING_WIDTH: Val = Val::Px(FOCUS_RING_WIDTH_PX);

    /// Clearance between a control's edge and its focus ring.
    pub const FOCUS_RING_OFFSET: Val = Val::Px(FOCUS_RING_OFFSET_PX);

    /// [`FOCUS_RING_OFFSET`] for a ring drawn inside the control's box: the same
    /// clearance measured inwards from the edge, so an inset ring reads the same
    /// as an outset one. Bevy takes the negative offset as "in from the edge".
    pub const FOCUS_RING_INSET_OFFSET: Val = Val::Px(-(FOCUS_RING_WIDTH_PX + FOCUS_RING_OFFSET_PX));

    /// Tight spacing for dense chrome: tooltips, popups, menu strips, tool
    /// buttons, and the interiors of sections and radio groups.
    pub const SPACE_TIGHT: Val = em_from_px(3.0);

    /// Standard spacing, gap and padding alike: between controls, inside a
    /// control (a button caption, a field's text, an option row, a tab label),
    /// and around a container's body. One step, so a row of controls is spaced
    /// the way its controls are inset.
    pub const SPACE: Val = em_from_px(6.0);

    /// Knob diameter (slider thumb, toggle knob)
    pub const KNOB_SIZE: Val = em_from_px(16.0);

    /// Scrollbar thumb width
    pub const SCROLLBAR_WIDTH: Val = em_from_px(6.0);

    /// Gutter reserved beside scrollable content for the scrollbar plus clearance
    pub const SCROLLBAR_GUTTER: Val = em_from_px(12.0);

    /// Default dialog pos
    pub const DEFAULT_DIALOG_POS: Val2 = Val2 {
        x: Val::Px(120.0),
        y: Val::Px(120.0),
    };

    /// Visible track strip thickness (the full-height node around it is the hit area).
    pub const SLIDER_TRACK_HEIGHT: Val = em_from_px(4.0);

    /// Width reserved for a glyph icon, em(1) so icons
    /// are square.
    pub const ICON_WIDTH: Val = Val::Em(1.0);
}

/// Global stacking layers, back to front. Only the order matters - bevy sorts
/// the roots by the value and then discards it.
pub mod z_order {
    /// Where bevy's `DialogStack` starts placing floating dialogs, mirroring its
    /// private `FLOATING_Z_BASE`; it owns this and the 39 layers above.
    pub const FLOATING_DIALOG: i32 = 50;

    /// The highest an app screen may take, one below the floating dialogs.
    /// [`z_index`](crate::imm::ImmResponse::z_index) clamps to it.
    pub const APP_MAX: i32 = FLOATING_DIALOG - 1;

    /// A modal and its barrier, one below the popups so a dropdown inside one
    /// still draws over it. Feathers' `FeathersDialog` uses the same layer.
    pub const MODAL: i32 = 99;

    /// The floor of the popup band: popups, menus and select dropdowns, one
    /// layer per level of nesting so a popup opened inside another draws over it.
    pub const POPUP: i32 = 100;

    /// The ceiling of that band, one below the tooltips. A nesting deeper than
    /// the band is wide pins to it rather than climbing into them.
    pub const POPUP_MAX: i32 = TOOLTIP - 1;

    /// Tooltips, over everything; they take no picks.
    pub const TOOLTIP: i32 = 200;
}

/// A glyph from the embedded Lucide icon font.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct Icon {
    glyph: &'static str,
}

impl Icon {
    // The constructor is crate-internal so every Icon is a glyph from the table below.
    pub(crate) const fn lucide(glyph: &'static str) -> Self {
        Self { glyph }
    }

    /// The glyph's codepoint as text.
    pub const fn glyph(self) -> &'static str {
        self.glyph
    }

    /// The embedded font asset path the glyph is drawn from.
    pub const fn font_path(self) -> &'static str {
        fonts::LUCIDE
    }
}

