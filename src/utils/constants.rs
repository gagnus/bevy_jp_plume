/// The FontAwesome face a glyph is drawn from.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum FaFace {
    /// FontAwesome Solid.
    Solid,
    /// FontAwesome Regular.
    Regular,
}

impl FaFace {
    /// The embedded font asset path for this face.
    pub const fn font_path(self) -> &'static str {
        match self {
            FaFace::Solid => fonts::FA_SOLID,
            FaFace::Regular => fonts::FA_REGULAR,
        }
    }
}

/// A FontAwesome glyph paired with the face that can render it.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct FaIcon {
    glyph: &'static str,
    face: FaFace,
}

impl FaIcon {
    // Constructors are crate-internal so every FaIcon is a glyph from the tables below.
    pub(crate) const fn solid(glyph: &'static str) -> Self {
        Self {
            glyph,
            face: FaFace::Solid,
        }
    }

    pub(crate) const fn regular(glyph: &'static str) -> Self {
        Self {
            glyph,
            face: FaFace::Regular,
        }
    }

    /// The glyph's codepoint as text.
    pub const fn glyph(self) -> &'static str {
        self.glyph
    }

    /// The face the glyph is drawn from.
    pub const fn face(self) -> FaFace {
        self.face
    }
}

